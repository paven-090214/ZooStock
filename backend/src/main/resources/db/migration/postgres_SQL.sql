
CREATE TABLE public.member (
    member_uid BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_name VARCHAR(50) NOT NULL,
    member_id VARCHAR(50) NOT NULL,
    member_password VARCHAR(255) NOT NULL,
    member_point BIGINT NOT NULL DEFAULT 0,
    member_created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_member
        PRIMARY KEY (member_uid),

    CONSTRAINT unique_member_id
        UNIQUE (member_id),

    CONSTRAINT check_member_point
        CHECK (member_point >= 0)
);

CREATE TABLE public.token (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    token_name VARCHAR(100) NOT NULL,
    token_price BIGINT NOT NULL,

    CONSTRAINT pk_token
        PRIMARY KEY (token_id),

    CONSTRAINT unique_token_name
        UNIQUE (token_name),

    CONSTRAINT check_token_price
        CHECK (token_price > 0)
);

