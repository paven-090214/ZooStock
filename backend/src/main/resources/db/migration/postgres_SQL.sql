CREATE TABLE public.token_holding (
    holding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_uid BIGINT NOT NULL,
    token_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    buy_price_avg NUMERIC(20, 2) NOT NULL,

    CONSTRAINT pk_token_holding
        PRIMARY KEY (holding_id),

    CONSTRAINT fk_holding_member
        FOREIGN KEY (member_uid)
        REFERENCES public.member(member_uid)
        ON DELETE RESTRICT,

    CONSTRAINT fk_holding_token
        FOREIGN KEY (token_id)
        REFERENCES public.token(token_id)
        ON DELETE RESTRICT,

    CONSTRAINT unique_holding_member_token
        UNIQUE (member_uid, token_id),

    CONSTRAINT check_holding_quantity
        CHECK (quantity > 0),

    CONSTRAINT check_holding_avg
        CHECK (buy_price_avg > 0)
);

CREATE TABLE public.trade_history (
    trade_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_uid BIGINT NOT NULL,
    token_id BIGINT NOT NULL,
    trade_price BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    traded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    trade_type VARCHAR(4) NOT NULL,

    CONSTRAINT pk_trade_history
        PRIMARY KEY (trade_id),

    CONSTRAINT fk_trade_member
        FOREIGN KEY (member_uid)
        REFERENCES public.member(member_uid)
        ON DELETE RESTRICT,

    CONSTRAINT fk_trade_token
        FOREIGN KEY (token_id)
        REFERENCES public.token(token_id)
        ON DELETE RESTRICT,

    CONSTRAINT check_trade_price
        CHECK (trade_price > 0),

    CONSTRAINT check_trade_quantity
        CHECK (quantity > 0),

    CONSTRAINT check_trade_type
        CHECK (trade_type IN ('BUY', 'SELL'))
);

-- Helps list a member's recent trades.
CREATE INDEX idx_trade_history_member_traded_at
    ON public.trade_history (member_uid, traded_at DESC);

-- Flyway V2: Price history (executed after V1)
CREATE TABLE public.price_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    price BIGINT NOT NULL,
    token_id BIGINT NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_price_history
        PRIMARY KEY (history_id),

    CONSTRAINT fk_price_history_token
        FOREIGN KEY (token_id)
        REFERENCES public.token(token_id)
        ON DELETE RESTRICT,

    CONSTRAINT check_price_history_price
        CHECK (price > 0)
);

-- Helps retrieve time-ordered prices for one token.
CREATE INDEX idx_price_history_token_recorded
    ON public.price_history (token_id, recorded_at DESC);
