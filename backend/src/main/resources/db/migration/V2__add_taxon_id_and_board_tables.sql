-- Flyway V2: Changes after the initial core schema.
-- Requires V1__create_core_tables.sql. This migration does not reset existing data.
ALTER TABLE public.token
    ADD COLUMN img_path TEXT;

-- Requires the existing member and token tables.
-- Existing tokens may have no external taxon ID, so this column remains nullable.
ALTER TABLE public.token
    ADD COLUMN taxon_id BIGINT;

ALTER TABLE public.token
    ADD CONSTRAINT unique_token_taxon_id UNIQUE (taxon_id);

CREATE TABLE public.board (
    board_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    member_uid BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    view_count BIGINT NOT NULL DEFAULT 0,
    board_created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_board
        PRIMARY KEY (board_id),

    CONSTRAINT fk_board_member
        FOREIGN KEY (member_uid)
        REFERENCES public.member(member_uid)
        ON DELETE RESTRICT,

    CONSTRAINT check_board_view_count
        CHECK (view_count >= 0)
);

CREATE TABLE public.board_like (
    like_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    board_id BIGINT NOT NULL,
    member_uid BIGINT NOT NULL,

    CONSTRAINT pk_board_like
        PRIMARY KEY (like_id),

    -- Deleting a post also removes its likes.
    CONSTRAINT fk_board_like_board
        FOREIGN KEY (board_id)
        REFERENCES public.board(board_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_board_like_member
        FOREIGN KEY (member_uid)
        REFERENCES public.member(member_uid)
        ON DELETE RESTRICT,

    -- One member can like a post only once.
    CONSTRAINT unique_board_like_board_member
        UNIQUE (board_id, member_uid)
);

-- Token price history.
CREATE TABLE public.price_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    price BIGINT NOT NULL,
    token_id BIGINT NOT NULL,
    recorded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_price_history
        PRIMARY KEY (history_id),

    CONSTRAINT fk_price_history_token
        FOREIGN KEY (token_id)
        REFERENCES public.token(token_id)
        ON DELETE RESTRICT,

    CONSTRAINT check_price_history_price
        CHECK (price > 0)
);

-- Helps retrieve time-ordered prices for one token.
CREATE INDEX idx_price_history_token_recorded
    ON public.price_history (token_id, recorded_at DESC);
